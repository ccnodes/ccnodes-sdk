#!/usr/bin/env node
// Regenerate src/chains-snapshot.ts from the live /v1/chains.
//
// The snapshot is the SDK's offline default: it lets a client know every chain
// on day one without a network call. It is refreshed lazily at runtime (see
// src/manifest.ts), so a stale snapshot costs one request, never correctness.
// Live status (tip height, sync) is stripped — it would be wrong by the time
// anyone installed the package.
import { writeFileSync } from "node:fs";

const base = (process.env.CCNODES_BASE_URL || "https://ccnodes.net/explorer/v1").replace(/\/$/, "");
const res = await fetch(base + "/chains", { headers: { "x-ccnodes-client": "ccnodes-sdk/snapshot" } });
if (!res.ok) throw new Error(`GET /chains -> HTTP ${res.status}`);
const chains = (await res.json()).map(({ status, ...rest }) => rest);
const ids = chains.map((c) => c.id).sort();

const src = `// GENERATED by scripts/snapshot-chains.mjs — do not edit by hand.
// Source: ${base}/chains on ${new Date().toISOString().slice(0, 10)} (${chains.length} chains: ${ids.join(", ")})
import type { Chain } from "./types.js";

export const CHAINS_SNAPSHOT: readonly Chain[] = ${JSON.stringify(chains, null, 2)};
`;
writeFileSync(new URL("../src/chains-snapshot.ts", import.meta.url), src);
console.log(`wrote ${chains.length} chains: ${ids.join(", ")}`);
